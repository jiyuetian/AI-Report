"""P 方案补充硬约束：检查器「只拦病态，不评判好坏」。
来源：H4 反方 3 —— 过度检查会掏空 AI 的存在意义（数值被覆盖、选型被检查后，AI 只剩"啥也没干"）。
"""
import io
import sys

P = 'night3/plans/P_ai_result_check.md'
s = io.open(P, encoding='utf-8').read()

MARK = '只拦病态，不评判好坏'
ANCHOR = '**处置策略（重要）**：不一致时**不一律删除**，分三档：'

ADD = '''### ⚠️ 检查器的权力边界（H4 反方 3 补充，本方案原先的缺口）

**只拦病态，不评判好坏。**

反方观点：如果对账后一律用实算值覆盖、对选型一律用检查器把关，那 AI 只剩"啥也没干"——
数值是数据库算的、字段是校验器把关的、图型是规则引擎兜底的，**AI 到底干了什么？**
过度检查会掏空 AI 的存在意义。

界线必须这样划：

| 维度 | 谁说了算 | 检查器的权限 |
|---|---|---|
| **数值**（KPI 值、聚合结果） | **数据**（实算） | ✅ 对账并覆盖 —— AI 不该编数字 |
| **字段是否存在 / 是否为空 / 基数是否病态** | **数据**（客观事实） | ✅ 拦 —— 是事实判断，不是审美 |
| **选哪张图、怎么构图、讲什么故事** | **AI** | ❌ **不评判** —— 只拦"画不出来"，不评判"画得好不好" |
| **图表标题措辞、分析叙事** | **AI** | ❌ **不评判**（S4b 只做数字对账与占位符检测） |

**落到代码上的硬约束**：
- `VisualEvaluator`（`visual_evaluator.py:8`，目前闲置未接线）**若接入，只能做病态检测**
  （空图 / 单值 / 基数爆炸 / 类型错配），**禁止做"美观度""合理性"打分**
- 检查器**不得因为"我觉得这张图意义不大"而丢弃** —— 丢弃理由必须是可枚举的客观判据
- 剔除率若 > 15%，视为检查过严，需放宽（见验收 V7 / H5 工单 T3-2 V4）

'''

if MARK in s:
    print('[skip] already applied')
    sys.exit(0)
if s.count(ANCHOR) != 1:
    print('[fail] anchor count=%d' % s.count(ANCHOR))
    sys.exit(1)
s = s.replace(ANCHOR, ADD + ANCHOR)
io.open(P, 'w', encoding='utf-8').write(s)
print('[ok] chars =', len(s))
